const HEADER_NAME = /^[!#$%&'*+.^_`|~0-9A-Za-z-]{1,100}$/;

function field(name: string, message: string): never {
  throw new HttpError(invalid(name, message));
}

/**
 * Validates a `Verify` object from a create request. Returns the stored config and, when the
 * caller supplied one, its secret (otherwise the relay generates it, when the preset allows).
 */
export function parseVerify(raw: unknown): { config: VerifyConfig; secret: string | null; verifyToken: string | null } {
  if (typeof raw !== "object" || raw === null || Array.isArray(raw)) field("verify", "verify must be an object.");
  const v = raw as Record<string, unknown>;
  const preset = v.preset;
  if (typeof preset !== "string" || !(PRESETS as readonly string[]).includes(preset)) {
    field("verify.preset", `verify.preset must be one of ${PRESETS.join(", ")}.`);
  }
  const p = preset as Preset;
  const spec = SPECS[p];
  const strict = v.strict === undefined ? false : v.strict;
  if (typeof strict !== "boolean") field("verify.strict", "verify.strict must be true or false.");
  if (strict && p === "unverified") field("verify.strict", "An unverified hook has nothing to verify on your devices.");
  // A token proves only that the sender knows it, and covers no content: a device given the token
  // could check nothing the relay couldn't fake, so devices refuse to verify strict token hooks.
  if (strict && p === "token") field("verify.strict", "A token hook can't be strict: the token signs nothing a device could check.");

  let secret: string | null = null;
  if (v.secret !== undefined) {
    if (spec.secret === "none") field("verify.secret", "The unverified preset takes no secret.");
    if (spec.secret === "public-key") field("verify.secret", "This preset takes the sender's publicKey, not a secret.");
    if (strict) field("verify.secret", "A strict hook's secret stays on your devices; the relay never holds it.");
    if (typeof v.secret !== "string" || v.secret.length < 8 || v.secret.length > 512) {
      field("verify.secret", "verify.secret must be a string of 8 to 512 characters.");
    }
    secret = v.secret;
    if (spec.secret === "generated-whsec" && !whsecKey(secret)) {
      field("verify.secret", "verify.secret must be whsec_ followed by base64 (at least 16 bytes).");
    }
  } else if (spec.secret === "provided" && !strict) {
    field("verify.secret", `The ${p} preset needs the signing secret ${p} gives you; the relay can't generate it.`);
  }

  const config: VerifyConfig = { preset: p };
  if (spec.secret === "public-key") {
    if (v.publicKey === undefined) {
      if (!strict) field("verify.publicKey", "verify.publicKey must be the sender's whpk_ public key.");
    } else {
      if (strict) field("verify.publicKey", "A strict hook's key stays on your devices.");
      if (typeof v.publicKey !== "string" || !whpkKey(v.publicKey)) {
        field("verify.publicKey", "verify.publicKey must be whpk_ followed by a base64 Ed25519 public key (32 bytes).");
      }
      config.publicKey = v.publicKey;
    }
  } else if (v.publicKey !== undefined) {
    field("verify.publicKey", "Only standard-webhooks-ed25519 takes publicKey.");
  }

  if (p === "hmac") {
    if (typeof v.header !== "string" || !HEADER_NAME.test(v.header)) {
      field("verify.header", "verify.header must be a header name.");
    }
    config.header = v.header.toLowerCase();
    const algorithm = v.algorithm ?? "sha256";
    if (algorithm !== "sha256" && algorithm !== "sha1") field("verify.algorithm", "verify.algorithm must be sha256 or sha1.");
    config.algorithm = algorithm;
    const encoding = v.encoding ?? "hex";
    if (encoding !== "hex" && encoding !== "base64") field("verify.encoding", "verify.encoding must be hex or base64.");
    config.encoding = encoding;
    if (v.prefix !== undefined) {
      if (typeof v.prefix !== "string" || v.prefix.length > 32) field("verify.prefix", "verify.prefix must be a short string.");
      if (v.prefix) config.prefix = v.prefix;
    }
  } else if (p === "token") {
    const header = v.header ?? "authorization";
    if (typeof header !== "string" || !HEADER_NAME.test(header)) field("verify.header", "verify.header must be a header name.");
    config.header = header.toLowerCase();
  }
  // Meta's verify token: the string the provider's GET handshake must carry. Generated when absent;
  // either way it is kept only as a keyed hash and never returned after creation.
  let verifyToken: string | null = null;
  if (v.verifyToken !== undefined) {
    if (!spec.getHandshake) field("verify.verifyToken", "Only the meta preset takes verifyToken.");
    if (typeof v.verifyToken !== "string" || !VERIFY_TOKEN.test(v.verifyToken)) {
      field("verify.verifyToken", "verify.verifyToken must be 8 to 200 printable characters, without spaces.");
    }
    verifyToken = v.verifyToken;
  }
  if (strict) config.strict = true;
  return { config, secret, verifyToken };
}

const VERIFY_TOKEN = /^[\x21-\x7e]{8,200}$/;

/** Whether the relay holds a secret for a hook with this config (never for a strict hook). */
export function presetTakesSecret(p: Preset, strict = false): boolean {
  const s = SPECS[p].secret;
  return !strict && s !== "none" && s !== "public-key";
}

/** Whether the relay may generate this preset's secret (otherwise the provider issues it). */
export function relayGeneratesSecret(p: Preset): boolean {
  const s = SPECS[p].secret;
  return s === "generated" || s === "generated-whsec";
}

/** A fresh signing secret: 32 random bytes, in the form the provider expects. */
export function generateSecret(p: Preset): string {
  const bytes = randomBytes(32);
  return SPECS[p].secret === "generated-whsec" ? `whsec_${toBase64(bytes)}` : toBase64Url(bytes);
}

function whsecKey(secret: string): Uint8Array<ArrayBuffer> | null {
  if (!secret.startsWith("whsec_")) return null;
  const key = fromBase64(secret.slice("whsec_".length));
  return key && key.byteLength >= 16 ? key : null;
}

function whpkKey(key: string): Uint8Array<ArrayBuffer> | null {
  if (!key.startsWith("whpk_")) return null;
  const raw = fromBase64(key.slice("whpk_".length));
  return raw && raw.byteLength === 32 ? raw : null;
}

export interface Delivery {
  body: Uint8Array<ArrayBuffer>;
  headers: Headers;
  /** Unix ms. */
  now: number;
  /** The public URL the relay was reached at, exactly (Twilio signs it). */
  url?: string;
}

export interface Verdict {
  ok: boolean;
  verified: boolean;
  /**
   * Per-hook replay keys, empty for presets that don't dedupe. A delivery is a duplicate when any of
   * them was seen before; all of them are marked in the same transaction as the append.
   */
  dedupeKeys: string[];
  /** The provider's event type, capped at 200 characters. Signed or not: see `EVENT_TYPE_SOURCE`. */
  eventType: string | null;
}

/** Event types are labels: anything longer is cut. */
export const EVENT_TYPE_MAX = 200;

const REFUSED: Verdict = { ok: false, verified: false, dedupeKeys: [], eventType: null };

/** The effective spec of a hook: the generic hmac preset takes its header and algorithm from the config. */
function effectiveSpec(config: VerifyConfig): Spec {
  const spec = SPECS[config.preset];
  if (config.preset !== "hmac") return spec;
  return {
    ...spec,
    mac: config.algorithm === "sha1" ? "hmac-sha1" : "hmac-sha256",
    sig: {
      header: config.header ?? "",
      format: { kind: "single", prefix: config.prefix ?? "" },
      encoding: config.encoding ?? "hex",
    },
  };
}

/**
 * Whether the hook's deliveries carry a signed timestamp the relay checks. Without one, a captured
 * genuine delivery verifies forever, so its body-hash replay mark is kept far longer (PROTOCOL §4).
 */
export function signsTimestamp(config: VerifyConfig): boolean {
  return effectiveSpec(config).timestamp !== undefined;
}

/** Parses Stripe-style `k=v,k=v` parameters; every value of a repeated key is kept. */
function sigParams(value: string): Map<string, string[]> {
  const out = new Map<string, string[]>();
  for (const part of value.split(",")) {
    const eq = part.indexOf("=");
    if (eq <= 0) continue;
    const k = part.slice(0, eq).trim();
    const list = out.get(k) ?? [];
    list.push(part.slice(eq + 1).trim());
    out.set(k, list);
  }
  return out;
}

/** The candidate signatures in the header, decoded; empty when there is none or it's malformed. */
function candidates(spec: Spec, headers: Headers): { sigs: Uint8Array<ArrayBuffer>[]; params: Map<string, string[]> } {
  const params = new Map<string, string[]>();
  if (!spec.sig) return { sigs: [], params };
  const value = headers.get(spec.sig.header);
  if (value === null) return { sigs: [], params };
  const encoding = spec.sig.encoding;
  const decode = (s: string) => (encoding === "hex" ? fromHex(s) : fromBase64(s));
  let raw: string[];
  const f = spec.sig.format;
  if (f.kind === "single") {
    const prefix = f.prefix ?? "";
    if (!value.startsWith(prefix)) return { sigs: [], params };
    raw = [value.slice(prefix.length).trim()];
  } else if (f.kind === "versioned") {
    raw = value
      .split(" ")
      .filter((s) => s.startsWith(`${f.version},`))
      .map((s) => s.slice(f.version.length + 1));
  } else {
    const parsed = sigParams(value);
    for (const [k, v] of parsed) params.set(k, v);
    raw = parsed.get(f.param) ?? [];
  }
  const sigs = raw.map(decode).filter((b): b is Uint8Array<ArrayBuffer> => b !== null && b.byteLength > 0);
  return { sigs, params };
}

function parseJson(body: Uint8Array): unknown {
  try {
    return JSON.parse(new TextDecoder("utf-8", { fatal: true, ignoreBOM: false }).decode(body)) as unknown;
  } catch {
    return undefined;
  }
}

/** A dotted path into parsed JSON; only strings and finite numbers count. */
function bodyPath(json: unknown, path: string): string | number | null {
  let v: unknown = json;
  for (const k of path.split(".")) {
    if (typeof v !== "object" || v === null || Array.isArray(v)) return null;
    v = (v as Record<string, unknown>)[k];
  }
  if (typeof v === "string") return v;
  if (typeof v === "number" && Number.isFinite(v)) return v;
  return null;
}

/** Code-point order, as Python's `sorted` (Twilio's reference library) sorts strings. */
function codePointCompare(a: string, b: string): number {
  const x = [...a];
  const y = [...b];
  for (let i = 0; i < Math.min(x.length, y.length); i++) {
    const d = x[i]!.codePointAt(0)! - y[i]!.codePointAt(0)!;
    if (d !== 0) return d;
  }
  return x.length - y.length;
}

/**
 * The strings Twilio may have signed for this request: the URL (as reached, without its port, and
 * with the scheme's default port, as Twilio's own libraries try) followed, for a form body, by every
 * parameter name and value: names sorted, each name's distinct values sorted. A JSON body is covered
 * by `bodySHA256` in the URL, which must match the body's hash. Null when nothing can be signed.
 */
export async function twilioSigned(d: Delivery): Promise<string[] | null> {
  if (!d.url) return null;
  let url: URL;
  try {
    url = new URL(d.url);
  } catch {
    return null;
  }
  const ct = (d.headers.get("content-type") ?? "").toLowerCase();
  let suffix = "";
  const bodyHash = url.searchParams.get("bodySHA256");
  if (bodyHash !== null) {
    if (!constantTimeEqual(utf8(bodyHash.toLowerCase()), utf8(await sha256Hex(d.body)))) return null;
  } else if (ct.startsWith("application/x-www-form-urlencoded")) {
    const byName = new Map<string, Set<string>>();
    for (const [k, v] of new URLSearchParams(new TextDecoder().decode(d.body))) {
      const set = byName.get(k) ?? new Set<string>();
      set.add(v);
      byName.set(k, set);
    }
    for (const name of [...byName.keys()].sort(codePointCompare)) {
      for (const value of [...byName.get(name)!].sort(codePointCompare)) suffix += name + value;
    }
  } else if (d.body.byteLength > 0) {
    // A body that is neither a form nor covered by bodySHA256 isn't covered by the signature at all.
    return null;
  }
  const defaultPort = url.protocol === "https:" ? "443" : "80";
  const withoutPort = new URL(url);
  withoutPort.port = "";
  // WHATWG URLs drop a default port when serialising, so this one is written out by hand.
  const withPort = `${url.protocol}//${url.hostname}:${url.port || defaultPort}${url.pathname}${url.search}`;
  return [...new Set([d.url, withoutPort.toString(), withPort])].map((u) => u + suffix);
}

/** The bytes the provider signed, or null when a part is missing. */
function signedBytes(spec: Spec, d: Delivery, params: Map<string, string[]>): Uint8Array<ArrayBuffer> | null {
  const parts: Uint8Array[] = [];
  for (const part of spec.signed) {
    if ("body" in part) parts.push(d.body);
    else if ("text" in part) parts.push(utf8(part.text));
    else if ("header" in part) {
      const v = d.headers.get(part.header);
      if (v === null) return null;
      parts.push(utf8(v));
    } else if ("sigParam" in part) {
      const v = params.get(part.sigParam);
      if (!v || v.length !== 1) return null;
      parts.push(utf8(v[0]!));
    } else return null;
  }
  return concatBytes(...parts);
}

/** The timestamp in ms; undefined when the preset has none, null when it's missing or malformed. */
function timestampMs(spec: Spec, d: Delivery, params: Map<string, string[]>, json: () => unknown): number | null | undefined {
  const t = spec.timestamp;
  if (!t) return undefined;
  let raw: string | number | null;
  if ("header" in t) raw = d.headers.get(t.header);
  else if ("sigParam" in t) {
    const v = params.get(t.sigParam);
    raw = v?.length === 1 ? v[0]! : null;
  } else raw = bodyPath(json(), t.bodyField);
  if (raw === null) return null;
  const s = String(raw);
  if (!/^\d{1,16}$/.test(s)) return null;
  return t.unit === "s" ? Number(s) * 1000 : Number(s);
}

function withinTolerance(spec: Spec, ts: number | null | undefined, now: number): boolean {
  if (ts === undefined) return true;
  if (ts === null) return false;
  return Math.abs(now - ts) <= spec.timestamp!.toleranceS * 1000;
}

function keyBytes(spec: Spec, secret: string): Uint8Array<ArrayBuffer> | null {
  if (spec.key === "whsec") return whsecKey(secret);
  if (spec.key === "whpk") return whpkKey(secret);
  return utf8(secret);
}

/** Whether any key verifies any candidate. Every pair is checked, so timing doesn't reveal which matched. */
async function anyMatch(
  spec: Spec,
  keys: string[],
  sigs: Uint8Array<ArrayBuffer>[],
  signed: Uint8Array<ArrayBuffer>[],
): Promise<boolean> {
  let ok = false;
  for (const s of keys) {
    const key = keyBytes(spec, s);
    if (!key) continue;
    if (spec.mac === "ed25519") {
      let pk: CryptoKey;
      try {
        pk = await crypto.subtle.importKey("raw", key, { name: "Ed25519" }, false, ["verify"]);
      } catch {
        continue;
      }
      for (const msg of signed) {
        for (const sig of sigs) if (sig.byteLength === 64) ok = (await crypto.subtle.verify("Ed25519", pk, sig, msg)) || ok;
      }
      continue;
    }
    const algorithm = spec.mac === "hmac-sha1" ? "SHA-1" : "SHA-256";
    for (const msg of signed) {
      const expected = await hmac(algorithm, key, msg);
      for (const sig of sigs) ok = constantTimeEqual(expected, sig) || ok;
    }
  }
  return ok;
}

async function dedupeKeys(spec: Spec, d: Delivery, json: () => unknown, strict: boolean): Promise<string[]> {
  const keys: string[] = [];
  for (const rule of spec.dedupe) {
    if ("bodyHash" in rule) keys.push(`body:${await sha256Hex(d.body)}`);
    // In strict mode nothing unverified may burn a mark that a genuine delivery would need later:
    // only the body hash is used (a forger can't predict a future genuine body).
    else if (strict) continue;
    else if ("header" in rule) {
      const v = d.headers.get(rule.header);
      if (v) keys.push(`${rule.signed ? "id" : "delivery"}:${v.slice(0, 200)}`);
    } else {
      const v = bodyPath(json(), rule.bodyField);
      if (v !== null) keys.push(`id:${String(v).slice(0, 200)}`);
    }
  }
  if (strict && keys.length === 0 && spec.mac !== "token") keys.push(`body:${await sha256Hex(d.body)}`);
  return keys;
}

function eventType(spec: Spec, d: Delivery, json: () => unknown, strict: boolean): string | null {
  const src = spec.eventType;
  if (!src) return null;
  if ("header" in src) return d.headers.get(src.header)?.slice(0, EVENT_TYPE_MAX) ?? null;
  // A strict hook's relay never reads the body: the device fills the type in after verifying.
  if (strict) return null;
  for (const path of src.bodyFields) {
    const v = bodyPath(json(), path);
    if (typeof v === "string") return v.slice(0, EVENT_TYPE_MAX);
  }
  return null;
}

/**
 * Verifies one delivery. `secrets` holds every secret that is currently valid (the current one, and
 * the previous one during a rotation's overlap), and any of them may match. A strict hook is only
 * checked for what needs no secret (`checkStrict`).
 */
export async function verifyDelivery(config: VerifyConfig, secrets: string[], d: Delivery): Promise<Verdict> {
  if (config.strict) return checkStrict(config, d);
  const spec = effectiveSpec(config);
  let parsed: unknown;
  let didParse = false;
  const json = () => {
    if (!didParse) {
      parsed = parseJson(d.body);
      didParse = true;
    }
    return parsed;
  };

  if (spec.mac === "none") return { ok: true, verified: false, dedupeKeys: [], eventType: null };
  if (spec.mac === "token") {
    const header = config.header ?? "authorization";
    const value = d.headers.get(header) ?? "";
    let presented = value;
    if (header === "authorization") {
      const space = value.indexOf(" ");
      if (space < 0 || value.slice(0, space).toLowerCase() !== "bearer") return REFUSED;
      presented = value.slice(space + 1).trim();
    }
    const given = utf8(presented);
    let ok = false;
    for (const s of secrets) ok = constantTimeEqual(utf8(s), given) || ok;
    return ok ? { ok: true, verified: true, dedupeKeys: [], eventType: null } : REFUSED;
  }

  const { sigs, params } = candidates(spec, d.headers);
  if (sigs.length === 0) return REFUSED;
  let signed: Uint8Array<ArrayBuffer>[];
  if (spec.signed.some((p) => "twilio" in p)) {
    const strings = await twilioSigned(d);
    if (!strings) return REFUSED;
    signed = strings.map(utf8);
  } else {
    const one = signedBytes(spec, d, params);
    if (!one) return REFUSED;
    signed = [one];
  }
  const keys = spec.mac === "ed25519" ? (config.publicKey ? [config.publicKey] : []) : secrets;
  if (!(await anyMatch(spec, keys, sigs, signed))) return REFUSED;
  // The timestamp is checked after the signature, so it is a signed one (Linear's is in the body).
  if (!withinTolerance(spec, timestampMs(spec, d, params, json), d.now)) return REFUSED;
  return { ok: true, verified: true, dedupeKeys: await dedupeKeys(spec, d, json, false), eventType: eventType(spec, d, json, false) };
}

/**
 * Strict mode at the edge (PLAN §4.4): no secret, so only the cheap checks. The signature header must
 * be there and well formed, and a timestamp the provider puts in a header must be in its window; the
 * body is never read. The event is stored `verified: false`, and the device verifies it.
 */
async function checkStrict(config: VerifyConfig, d: Delivery): Promise<Verdict> {
  const spec = effectiveSpec(config);
  const none = () => undefined;
  if (spec.mac === "token") {
    if (!d.headers.get(config.header ?? "authorization")) return REFUSED;
  } else {
    const { sigs, params } = candidates(spec, d.headers);
    if (sigs.length === 0) return REFUSED;
    if (spec.timestamp && !("bodyField" in spec.timestamp)) {
      if (!withinTolerance(spec, timestampMs(spec, d, params, none), d.now)) return REFUSED;
    }
  }
  return { ok: true, verified: false, dedupeKeys: await dedupeKeys(spec, d, none, true), eventType: eventType(spec, d, none, true) };
}

/**
 * Slack's endpoint check (`url_verification`), answered after the delivery verified (or, for a
 * strict hook, passed the edge's checks): the challenge echoed as plain text. Null when this isn't one.
 */
export function handshakeAnswer(config: VerifyConfig, body: Uint8Array): Response | null {
  if (SPECS[config.preset].handshake !== "slack-url-verification") return null;
  const v = parseJson(body);
  if (typeof v !== "object" || v === null || (v as { type?: unknown }).type !== "url_verification") return null;
  const challenge = (v as { challenge?: unknown }).challenge;
  if (typeof challenge !== "string" || challenge.length > 200 || !/^[A-Za-z0-9._~-]+$/.test(challenge)) return null;
  return new Response(challenge, {
    status: 200,
    headers: { "Content-Type": "text/plain; charset=utf-8", "Cache-Control": "no-store", "X-Content-Type-Options": "nosniff" },
  });
}

// `00hooks-origin` and `00hooks-hop` are what a 00hooks runner puts on its own outbound calls, so
// it can recognise its own call coming back and stop loops (PLAN §5.3). Like every kept header, they
// are the sender's claim; the runner only ever *drops* on them. Sealed like the rest.
const COMMON_HEADERS = ["content-type", "user-agent", "00hooks-origin", "00hooks-hop"];
const NEVER_KEPT = new Set([
  "cookie",
  "authorization",
  "proxy-authorization",
  "set-cookie",
  "x-hub-signature",
  "x-hub-signature-256",
  "webhook-signature",
  "stripe-signature",
  "x-slack-signature",
  "linear-signature",
  "x-shopify-hmac-sha256",
  "x-twilio-signature",
]);

/** A header that carries this hook's signature or token, whatever the preset calls it. */
function isCredentialHeader(config: VerifyConfig, name: string): boolean {
  return NEVER_KEPT.has(name) || ((config.preset === "hmac" || config.preset === "token") && name === config.header);
}

/**
 * The headers an event keeps: the preset's allowlist, lowercased; never cookies, credentials or
 * signatures. Every kept header is the sender's claim to the reader: once the signature is gone,
 * nothing lets the reader check one.
 */
export function keptHeaders(config: VerifyConfig, headers: Headers): Record<string, string> {
  const names = [...COMMON_HEADERS, ...SPECS[config.preset].keep];
  const out: Record<string, string> = {};
  for (const n of names) {
    if (isCredentialHeader(config, n)) continue;
    const v = headers.get(n);
    if (v !== null) out[n] = v.slice(0, 1024);
  }
  return out;
}

/**
 * The headers a strict hook seals for its devices: the kept ones, plus everything a device needs to
 * verify the provider's signature itself (the signature header, and any header the signed content
 * or the timestamp uses). They are sealed, so the relay's storage never holds them in the clear.
 */
export function strictHeaders(config: VerifyConfig, headers: Headers): Record<string, string> {
  const spec = effectiveSpec(config);
  const out = keptHeaders(config, headers);
  const extra = new Set<string>();
  if (spec.sig?.header) extra.add(spec.sig.header);
  if (spec.mac === "token") extra.add(config.header ?? "authorization");
  for (const p of spec.signed) if ("header" in p) extra.add(p.header);
  if (spec.timestamp && "header" in spec.timestamp) extra.add(spec.timestamp.header);
  for (const n of extra) {
    const v = headers.get(n);
    if (v !== null) out[n] = v.slice(0, 4096);
  }
  return out;
}

// ── Meta's GET handshake (PROTOCOL §4) ───────────────────────────────────────

/** A challenge echoed back: short, and only characters that can't make the answer anything else. */
const CHALLENGE = /^[A-Za-z0-9._~-]{1,200}$/;

/**
 * What a GET handshake asks: `hub.mode=subscribe`, the verify token it presents and the challenge to
 * echo. Null when the request isn't one (wrong mode, a missing or unsafe challenge).
 */
export function metaSubscribe(url: URL): { token: string; challenge: string } | null {
  const q = url.searchParams;
  if (q.get("hub.mode") !== "subscribe") return null;
  const token = q.get("hub.verify_token");
  const challenge = q.get("hub.challenge");
  if (token === null || challenge === null || !CHALLENGE.test(challenge)) return null;
  return { token, challenge };
}

export function challengeAnswer(challenge: string): Response {
  return new Response(challenge, {
    status: 200,
    headers: { "Content-Type": "text/plain; charset=utf-8", "Cache-Control": "no-store", "X-Content-Type-Options": "nosniff" },
  });
}

/** A fresh verify token: 24 random bytes, base64url (32 characters). */
export function generateVerifyToken(): string {
  return toBase64Url(randomBytes(24));
}

// ── Offline notices (PROTOCOL §4a) ───────────────────────────────────────────

/** A hook's offline notice: the text, and how long no device may have been connected first. */
export interface OfflineNotice {
  text: string;
  afterMinutes: number;
}

export const NOTICE_MAX_CHARS = 320;
export const NOTICE_MAX_MINUTES = 7 * 24 * 60;
/** One notice per sender per hook in this long. */
export const NOTICE_PER_SENDER_MS = 24 * 3600_000;

/** Whether a preset's provider takes a reply in the HTTP response, so a notice can be sent. */
export function presetTakesNotice(p: Preset): boolean {
  return SPECS[p].notice !== undefined;
}

/** Validates `offlineNotice` from a create or update: null clears it. */
export function parseOfflineNotice(raw: unknown, preset: Preset): OfflineNotice | null {
  if (raw === null) return null;
  if (!presetTakesNotice(preset)) {
    field(
      "offlineNotice",
      `${preset} answers through an API call, not in the webhook's response, so the relay can't send a notice for it.`,
    );
  }
  if (typeof raw !== "object" || Array.isArray(raw)) field("offlineNotice", "offlineNotice must be an object or null.");
  const v = raw as Record<string, unknown>;
  const text = typeof v.text === "string" ? v.text.trim() : "";
  // Printable text and line breaks only: it goes back to the sender as it is.
  if (text.length < 1 || [...text].length > NOTICE_MAX_CHARS || /[\u0000-\u0009\u000b-\u001f\u007f]/.test(text)) {
    field("offlineNotice.text", `offlineNotice.text must be 1 to ${NOTICE_MAX_CHARS} characters of text.`);
  }
  const m = v.afterMinutes;
  if (typeof m !== "number" || !Number.isInteger(m) || m < 1 || m > NOTICE_MAX_MINUTES) {
    field("offlineNotice.afterMinutes", `offlineNotice.afterMinutes must be a whole number from 1 to ${NOTICE_MAX_MINUTES}.`);
  }
  return { text, afterMinutes: m as number };
}

/**
 * Who a delivery is from, for the once-a-day cap; null when it isn't a message a notice could answer
 * (a Twilio status callback or call, a Slack event rather than a slash command). Read only after
 * the delivery verified.
 */
export function noticeSender(config: VerifyConfig, body: Uint8Array, headers: Headers): string | null {
  const how = SPECS[config.preset].notice;
  if (!how) return null;
  const ct = (headers.get("content-type") ?? "").toLowerCase();
  if (!ct.startsWith("application/x-www-form-urlencoded")) return null;
  const form = new URLSearchParams(new TextDecoder().decode(body));
  if (how === "twiml") {
    // An incoming message: it has a MessageSid and a sender, and isn't a status callback.
    const from = form.get("From");
    if (!form.get("MessageSid") || form.has("MessageStatus") || !from) return null;
    return `from:${from.slice(0, 200)}`;
  }
  const team = form.get("team_id");
  const user = form.get("user_id");
  if (!form.get("command") || !team || !user) return null;
  return `user:${team.slice(0, 100)}:${user.slice(0, 100)}`;
}

function xmlEscape(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");
}

/**
 * The answer to a delivery the provider expects a reply to: TwiML for Twilio (empty, or the notice
 * as a `<Message>`), an ephemeral message for a Slack slash command. Null for everything else, which
 * gets the usual JSON.
 */
export function providerAnswer(config: VerifyConfig, notice: string | null, received: Record<string, unknown>): Response | null {
  const how = SPECS[config.preset].notice;
  if (how === "twiml") {
    const inner = notice === null ? "" : `<Message>${xmlEscape(notice)}</Message>`;
    return new Response(`<?xml version="1.0" encoding="UTF-8"?><Response>${inner}</Response>`, {
      status: 200,
      headers: { "Content-Type": "text/xml; charset=utf-8", "Cache-Control": "no-store" },
    });
  }
  if (how === "slack-command" && notice !== null) {
    return new Response(JSON.stringify({ response_type: "ephemeral", text: notice, ...received }), {
      status: 200,
      headers: { "Content-Type": "application/json; charset=utf-8", "Cache-Control": "no-store" },
    });
  }
  return null;
}
