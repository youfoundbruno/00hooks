// Provider presets (PROTOCOL §3): how a hook's deliveries are verified, deduplicated, typed, and
// which headers are kept. The presets are a declarative table (`SPECS`): which header carries the
// signature and how it is written, which bytes are signed, the key's form, the timestamp rule, the
// replay marks and where the event type comes from. One small interpreter (`verifyDelivery`) runs
// every entry, always over the raw bytes, and every comparison of a signature or token is
// constant-time. The CLI carries the same table for strict mode (`cli/hooks-client/src/presets.rs`),
// and both are held to the shared vectors in `fixtures/presets.v1.json`.

