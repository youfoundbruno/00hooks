export type Preset = (typeof PRESETS)[number];

/** The non-secret part of a hook's verification, as stored and as returned in `Hook.verify`. */
export interface VerifyConfig {
  preset: Preset;
  header?: string;
  algorithm?: "sha256" | "sha1";
  encoding?: "hex" | "base64";
  prefix?: string;
  /** standard-webhooks-ed25519: the sender's public key, `whpk_` + base64. Not a secret. */
  publicKey?: string;
  /** Verify on the devices (PLAN §4.4): the relay holds no secret and checks only the cheap things. */
  strict?: boolean;
}

/** One piece of the signed content. */
export type Part =
  | { body: true }
  | { text: string }
  | { header: string }
  /** A parameter of the signature header itself (Stripe's `t`). */
  | { sigParam: string }
  /** Twilio: the public URL, then every form parameter sorted (or the URL alone, for JSON). */
  | { twilio: true };

/** How the signature header is written. */
export type SigFormat =
  /** The whole value (after `prefix`) is one signature. */
  | { kind: "single"; prefix?: string }
  /** Space-separated `version,signature` pairs (Standard Webhooks); any one may match. */
  | { kind: "versioned"; version: string }
  /** Comma-separated `k=v` pairs (Stripe); every `param` value is a candidate. */
  | { kind: "params"; param: string };

export type DedupeRule = { header: string; signed: boolean } | { bodyField: string } | { bodyHash: true };

export interface Spec {
  /** Where the secret comes from: generated by the relay when absent, required from the provider, or a public key. */
  secret: "generated" | "generated-whsec" | "provided" | "public-key" | "none";
  /** The check. The generic hmac preset's algorithm and header come from the hook (`effectiveSpec`). */
  mac: "hmac-sha256" | "hmac-sha1" | "ed25519" | "token" | "none";
  /** The key bytes: the secret's UTF-8, a `whsec_`'s base64, or a `whpk_`'s base64. */
  key: "utf8" | "whsec" | "whpk";
  sig?: { header: string; format: SigFormat; encoding: "hex" | "base64" };
  signed: Part[];
  /** A signed timestamp and how far it may be from the relay's clock. */
  timestamp?: ({ header: string } | { sigParam: string } | { bodyField: string }) & { unit: "s" | "ms"; toleranceS: number };
  /** Replay marks; a delivery is a duplicate when any is seen. */
  dedupe: DedupeRule[];
  /** Where `eventType` comes from, first match wins. */
  eventType: { header: string } | { bodyFields: string[] } | null;
  eventTypeSource: "signed" | "claimed" | "none";
  /** Provider headers kept with the event (besides content-type and user-agent). */
  keep: string[];
  /** An endpoint check the preset answers after verification. */
  handshake?: "slack-url-verification";
  /**
   * An endpoint check made with a GET before the provider sends anything (Meta's `hub.challenge`):
   * answered at the edge when the request carries the hook's verify token. Never stored.
   */
  getHandshake?: "meta-subscribe";
  /**
   * The provider takes a reply in the HTTP response, so the relay can answer with the hook's
   * offline notice while no device is connected (PROTOCOL §4a). How to name the sender (for the
   * once-a-day cap) and how to write the answer.
   */
  notice?: "twiml" | "slack-command";
}

